export type TranslationKey = keyof (typeof translations)["en"];

interface LanguageContextValue {
  language: AppLanguage;
  direction: "ltr" | "rtl";
  setLanguage: (language: AppLanguage) => void;
  t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const STORAGE_KEY = "maploom-language";

function getInitialLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === "fr" || saved === "ar" || saved === "en") return saved;
  // First visit: follow the browser, defaulting to French for Moroccan visitors.
  const browser = (window.navigator.language || "").toLowerCase();
  if (browser.startsWith("ar")) return "ar";
  if (browser.startsWith("en") && !browser.endsWith("-ma")) return "en";
  return "fr";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>(getInitialLanguage);
  const direction = language === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
  }, [direction, language]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      direction,
      setLanguage,
      t: (key) => translations[language][key],
    }),
    [direction, language],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
